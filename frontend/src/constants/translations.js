export function translateLoanType(type, t) {
  if (!type) return '';
  const norm = String(type).toLowerCase().replace(/[-_ ]/g, '');
  if (norm.includes('personal')) return t ? t('loan_personal', 'Personal Loan') : 'Personal Loan';
  if (norm.includes('home')) return t ? t('loan_home', 'Home Loan') : 'Home Loan';
  if (norm.includes('business')) return t ? t('loan_business', 'Business Loan') : 'Business Loan';
  if (norm.includes('vehicle') || norm.includes('auto')) return t ? t('loan_vehicle', 'Vehicle Loan') : 'Vehicle Loan';
  if (norm.includes('education')) return t ? t('loan_education', 'Education Loan') : 'Education Loan';
  if (norm.includes('lap') || norm.includes('property')) return t ? t('loan_lap', 'Loan Against Property') : 'Loan Against Property';
  return `${type} Loan`;
}

